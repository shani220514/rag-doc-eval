"""Extract /v1/ paths from Markdown. HTTP methods are not part of the path."""
from __future__ import annotations

import re

_PATH_RE = re.compile(r"/(v1/[A-Za-z0-9_/{}.-]*)")


def extract_paths(text: str) -> list[str]:
    """Return unique paths starting with /v1/, punctuation stripped."""
    found: list[str] = []
    seen_set: set[str] = set()
    for match in _PATH_RE.finditer(text):
        raw = "/" + match.group(1)
        cleaned = raw.rstrip(".,;:)")
        if cleaned not in seen_set:
            seen_set.add(cleaned)
            found.append(cleaned)
    return found


def build_whitelist(md_texts: list[str]) -> list[str]:
    """Union of extract_paths over all synced markdown bodies, first-seen order."""
    acc: list[str] = []
    seen: set[str] = set()
    for body in md_texts:
        for p in extract_paths(body):
            if p not in seen:
                seen.add(p)
                acc.append(p)
    return acc


def whitelist_yaml(paths: list[str]) -> str:
    """YAML for eval/path_whitelist.yaml. Regenerated each eval; not an input of truth."""
    lines = [
        "# Generated by eval. Do not hand-edit as source of truth.",
        "paths:",
    ]
    for p in paths:
        lines.append(f"  - {p}")
    return "\n".join(lines) + "\n"
